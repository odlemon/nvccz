// @ts-nocheck
import { Request, Response } from "express";
import { AuthRequest } from "../middleware/authenticate";
import { InvoiceService, CreateInvoiceParams } from "../services/InvoiceService";
import { DebtorsAgeAnalysisService } from "../services/DebtorsAgeAnalysisService";
import { ResponseHelper } from "../utils/responseHelper";
import { logger } from "../utils/logger";
import { parseDate } from "../utils/dateHelper";

export class InvoiceController {
  /**
   * Create a new invoice
   */
  static async createInvoice(req: AuthRequest, res: Response): Promise<void> {
    try {
      const {
        customerId,
        amount,
        currencyId,
        invoiceDate,
        dueDate,
        description,
        items,
        isTaxable,
        notes
      } = req.body;
      // invoiceNumber is always auto-generated by the service; do not pass from client

      // Validate required fields with specifics
      const missing: string[] = [];
      if (!customerId) missing.push("customerId");
      if (!currencyId) missing.push("currencyId");
      if (!invoiceDate) missing.push("invoiceDate");
      if (!items || !Array.isArray(items) || items.length === 0) missing.push("items");

      if (missing.length) {
        ResponseHelper.badRequest(
          res,
          `Missing required fields: ${missing.join(", ")}`,
          JSON.stringify({ missingFields: missing })
        );
        return;
      }

      // Calculate total amount from items
      let calculatedAmount = 0;
      if (items && Array.isArray(items)) {
        calculatedAmount = items.reduce((total, item) => {
          const itemTotal = (item.quantity || 0) * (item.unitPrice || 0);
          return total + itemTotal;
        }, 0);
      }

      // Use calculated amount if no amount provided, otherwise use provided amount
      const finalAmount = amount !== undefined ? Number(amount) : calculatedAmount;

      // Validate amount
      if (Number(finalAmount) <= 0) {
        ResponseHelper.badRequest(res, "Amount must be greater than zero");
        return;
      }

      // Create description from items if not provided
      const finalDescription = description || `Invoice with ${items.length} item(s)`;
      const transactionDate = parseDate(invoiceDate);

      // Get user ID from request (set by auth middleware)
      const createdById = (req as any).user?.id;
      if (!createdById) {
        ResponseHelper.error(res, "User not authenticated", undefined, 401);
        return;
      }

      const invoiceParams: CreateInvoiceParams = {
        customerId,
        amount: Number(finalAmount),
        currencyId,
        transactionDate: transactionDate,
        description: finalDescription,
        items,
        isTaxable: Boolean(isTaxable),
        createdById,
        dueDate: dueDate ? parseDate(dueDate) : null,
      };

      const invoice = await InvoiceService.createInvoice(invoiceParams);

      logger.info("Invoice created successfully", {
        invoiceId: invoice.id,
        amount: invoice.amount,
        customerId: invoice.customerId,
        userId: createdById
      });

      ResponseHelper.success(res, "Invoice created successfully", invoice, 201);
    } catch (error: any) {
      logger.error("Error creating invoice", { error: error.message });
      ResponseHelper.error(res, `Failed to create invoice: ${error.message}`, undefined, 500);
    }
  }

  /**
   * Get invoice by ID
   */
  static async getInvoiceById(req: AuthRequest, res: Response): Promise<void> {
    try {
      const { id } = req.params;

      if (!id) {
        ResponseHelper.error(res, "Invoice ID is required", undefined, 400);
        return;
      }

      const invoice = await InvoiceService.getInvoiceById(id);

      if (!invoice) {
        ResponseHelper.error(res, "Invoice not found", undefined, 404);
        return;
      }

      // Ensure auto-generated invoiceNumber is always in response
      const data = { ...invoice, invoiceNumber: invoice.invoiceNumber ?? null };
      ResponseHelper.success(res, "Invoice retrieved successfully", data);
    } catch (error: any) {
      logger.error("Error getting invoice", { error: error.message });
      ResponseHelper.error(res, `Failed to get invoice: ${error.message}`, undefined, 500);
    }
  }

  /**
   * Get invoices with filtering and pagination
   */
  static async getInvoices(req: AuthRequest, res: Response): Promise<void> {
    try {
      const {
        page = 1,
        limit = 10,
        customerId,
        currencyId,
        startDate,
        endDate,
        status
      } = req.query;

      const params = {
        page: Number(page),
        limit: Number(limit),
        customerId: customerId as string,
        currencyId: currencyId as string,
        startDate: startDate ? new Date(startDate as string) : undefined,
        endDate: endDate ? new Date(endDate as string) : undefined,
        status: status as string
      };

      const result = await InvoiceService.getInvoices(params);
      // Ensure each invoice in list includes auto-generated invoiceNumber
      const data = {
        ...result,
        invoices: (result.invoices || []).map((inv: any) => ({ ...inv, invoiceNumber: inv.invoiceNumber ?? null }))
      };
      ResponseHelper.success(res, "Invoices retrieved successfully", data);
    } catch (error: any) {
      logger.error("Error getting invoices", { error: error.message });
      ResponseHelper.error(res, `Failed to get invoices: ${error.message}`, undefined, 500);
    }
  }

  /**
   * Update an invoice
   */
  static async updateInvoice(req: AuthRequest, res: Response): Promise<void> {
    try {
      const { id } = req.params;
      const updateData = req.body;

      if (!id) {
        ResponseHelper.error(res, "Invoice ID is required", undefined, 400);
        return;
      }

      // Validate amount if provided
      if (updateData.amount !== undefined && updateData.amount <= 0) {
        ResponseHelper.error(res, "Amount must be greater than zero", undefined, 400);
        return;
      }

      // Convert numeric fields
      if (updateData.amount !== undefined) {
        updateData.amount = Number(updateData.amount);
      }
      if (updateData.isTaxable !== undefined) {
        updateData.isTaxable = Boolean(updateData.isTaxable);
      }
      if (updateData.transactionDate !== undefined) {
        updateData.transactionDate = parseDate(updateData.transactionDate);
      }

      const updatedInvoice = await InvoiceService.updateInvoice(id, updateData);

      logger.info("Invoice updated successfully", {
        invoiceId: id,
        userId: (req as any).user?.id
      });

      ResponseHelper.success(res, "Invoice updated successfully", updatedInvoice);
    } catch (error: any) {
      logger.error("Error updating invoice", { error: error.message });
      ResponseHelper.error(res, `Failed to update invoice: ${error.message}`, undefined, 500);
    }
  }

  /**
   * Delete an invoice
   */
  static async deleteInvoice(req: AuthRequest, res: Response): Promise<void> {
    try {
      const { id } = req.params;

      if (!id) {
        ResponseHelper.error(res, "Invoice ID is required", undefined, 400);
        return;
      }

      await InvoiceService.deleteInvoice(id);

      logger.info("Invoice deleted successfully", {
        invoiceId: id,
        userId: (req as any).user?.id
      });

      ResponseHelper.success(res, "Invoice deleted successfully");
    } catch (error: any) {
      logger.error("Error deleting invoice", { error: error.message });
      ResponseHelper.error(res, `Failed to delete invoice: ${error.message}`, undefined, 500);
    }
  }

  /**
   * Get invoice summary statistics
   */
  static async getInvoiceSummary(req: AuthRequest, res: Response): Promise<void> {
    try {
      const { startDate, endDate, currencyId } = req.query;

      const params: any = {};
      if (startDate) params.startDate = new Date(startDate as string);
      if (endDate) params.endDate = new Date(endDate as string);
      if (currencyId) params.currencyId = currencyId as string;

      const summary = await InvoiceService.getInvoiceSummary(params);

      ResponseHelper.success(res, "Invoice summary retrieved successfully", summary);
    } catch (error: any) {
      logger.error("Error getting invoice summary", { error: error.message });
      ResponseHelper.error(res, `Failed to get invoice summary: ${error.message}`, undefined, 500);
    }
  }

  /**
   * Send invoice to customer (DRAFT -> SENT)
   */
  static async sendInvoice(req: AuthRequest, res: Response): Promise<void> {
    try {
      const { id } = req.params;

      if (!id) {
        ResponseHelper.error(res, "Invoice ID is required", undefined, 400);
        return;
      }

      const actingUser = (req as any).user;
      const invoice = await InvoiceService.sendInvoice(id, {
        user: actingUser,
        performedById: actingUser?.id,
      });

      logger.info("Invoice sent successfully", {
        invoiceId: invoice.id,
        status: invoice.status,
        userId: actingUser?.id
      });

      ResponseHelper.success(res, "Invoice sent successfully", invoice);
    } catch (error: any) {
      logger.error("Error sending invoice", { error: error.message });
      ResponseHelper.error(res, `Failed to send invoice: ${error.message}`, undefined, 500);
    }
  }

  /**
   * Record invoice payment (SENT or PARTIALLY_PAID -> PAID or PARTIALLY_PAID when same currency).
   */
  static async markAsPaid(req: AuthRequest, res: Response): Promise<void> {
    try {
      const { id } = req.params;
      const {
        paymentMethod = "BANK",
        paymentCurrencyId,
        paymentAmount,
        bankId,
        paymentExchangeRate
      } = req.body;

      if (!id) {
        ResponseHelper.error(res, "Invoice ID is required", undefined, 400);
        return;
      }

      const invoice = await InvoiceService.markAsPaid(id, {
        paymentMethod,
        paymentCurrencyId,
        paymentAmount:
          paymentAmount !== undefined && paymentAmount !== null && paymentAmount !== ""
            ? Number(paymentAmount)
            : undefined,
        bankId,
        paymentExchangeRate:
          paymentExchangeRate !== undefined && paymentExchangeRate !== null && paymentExchangeRate !== ""
            ? Number(paymentExchangeRate)
            : undefined
      });

      logger.info("Invoice marked as paid", {
        invoiceId: invoice.id,
        status: invoice.status,
        paymentMethod,
        userId: (req as any).user?.id
      });

      ResponseHelper.success(res, "Invoice marked as paid successfully", invoice);
    } catch (error: any) {
      logger.error("Error marking invoice as paid", { error: error.message });
      ResponseHelper.error(res, `Failed to mark invoice as paid: ${error.message}`, undefined, 500);
    }
  }

  /**
   * Void invoice (any status -> VOID)
   */
  static async voidInvoice(req: AuthRequest, res: Response): Promise<void> {
    try {
      const { id } = req.params;
      const { reason } = req.body; // Optional reason for voiding

      if (!id) {
        ResponseHelper.error(res, "Invoice ID is required", undefined, 400);
        return;
      }

      const invoice = await InvoiceService.voidInvoice(id, reason, req.user?.id);

      logger.info("Invoice voided successfully", {
        invoiceId: invoice.id,
        status: invoice.status,
        reason,
        userId: (req as any).user?.id
      });

      ResponseHelper.success(res, "Invoice voided successfully", invoice);
    } catch (error: any) {
      logger.error("Error voiding invoice", { error: error.message });
      ResponseHelper.error(res, `Failed to void invoice: ${error.message}`, undefined, 500);
    }
  }

  /**
   * Debtors age analysis (open AR). GET ?asOfDate=YYYY-MM-DD
   */
  static async getDebtorsAgeAnalysis(req: AuthRequest, res: Response): Promise<void> {
    try {
      const raw = req.query.asOfDate as string | undefined;
      const asOfDate =
        raw && !Number.isNaN(Date.parse(raw)) ? new Date(raw) : undefined;
      const report = await DebtorsAgeAnalysisService.generate({ asOfDate });
      ResponseHelper.success(res, "Debtors age analysis generated successfully", report);
    } catch (error: any) {
      logger.error("Error generating debtors age analysis", { error: error.message });
      ResponseHelper.error(
        res,
        `Failed to generate debtors age analysis: ${error.message}`,
        undefined,
        500
      );
    }
  }
} 