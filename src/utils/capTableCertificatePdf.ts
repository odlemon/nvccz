// @ts-nocheck
const PDFDocument = require("pdfkit");

export type StockCertificatePdfInput = {
  companyName: string;
  stakeholderName: string;
  shareClassName: string;
  quantity: number;
  certificateNumber: string;
  issuanceDateLabel: string;
  sha256Preview: string;
};

export function buildStockCertificatePdfBuffer(input: StockCertificatePdfInput): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 50 });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc.fontSize(22).fillColor("#1e293b").text("STOCK CERTIFICATE", { align: "center" });
    doc.moveDown(0.5);
    doc.fontSize(10).fillColor("#64748b").text("Arcus Capitalisation Table — tamper-evident record", {
      align: "center",
    });
    doc.moveDown(1.5);

    doc.fontSize(12).fillColor("#000000");
    doc.text(`This certifies that ${input.stakeholderName}`);
    doc.text(`is the registered holder of ${input.quantity.toLocaleString()} shares`);
    doc.text(`of ${input.shareClassName} in ${input.companyName}.`);
    doc.moveDown(1);

    doc.fontSize(10);
    doc.text(`Certificate No: ${input.certificateNumber}`);
    doc.text(`Issuance Date: ${input.issuanceDateLabel}`);
    doc.moveDown(2);

    doc.fontSize(8).fillColor("#475569");
    doc.text(`SHA-256: ${input.sha256Preview}`, { width: 500 });
    doc.text("This document is generated by Arcus ERP Cap Table Management.", { width: 500 });

    doc.end();
  });
}
