// @ts-nocheck
const PDFDocument = require("pdfkit");
import type { QuarterlyLpMetrics } from "./QuarterlyStatementMetricsService";
import { loadCapitalCallAccountingLetterhead } from "./capitalCallAccountingLetterhead";

function fmt(n: number, ccy = "USD") {
  return `${ccy === "ZIG" ? "ZiG " : "$"}${n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

export async function buildQuarterlyClientStatementPdfBuffer(
  metrics: QuarterlyLpMetrics
): Promise<Buffer> {
  const letterhead = await loadCapitalCallAccountingLetterhead();
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: "A4" });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    if (letterhead) {
      doc.font("Helvetica").fontSize(12).text(letterhead.displayName, { align: "right" });
      for (const line of letterhead.detailLines) {
        doc.fontSize(9).fillColor("#444444").text(line, { align: "right" });
      }
      doc.fillColor("#000000").moveDown(0.5);
    }

    doc.font("Helvetica-Bold").fontSize(16).text("Quarterly Client Statement", { align: "center" });
    doc.moveDown(0.3);
    doc
      .font("Helvetica")
      .fontSize(11)
      .text(`${metrics.fundName} · Q ending ${metrics.periodEnd}`, { align: "center" });
    doc.moveDown(1);

    doc.font("Helvetica-Bold").fontSize(12).text(`Limited Partner: ${metrics.lpLegalName}`);
    doc.moveDown(0.5);

    const rows: Array<[string, string, string]> = [
      ["Total Commitment", fmt(metrics.totalCommitmentUsd), fmt(metrics.totalCommitmentZig, "ZIG")],
      ["Total Called", fmt(metrics.totalPaidInUsd), fmt(metrics.totalPaidInZig, "ZIG")],
      ["Cumulative Distributions", fmt(metrics.totalDistributionsUsd), fmt(metrics.totalDistributionsZig, "ZIG")],
      ["Estimated NAV", fmt(metrics.navUsd), fmt(metrics.navZig, "ZIG")],
      ["DPI", metrics.dpi.toFixed(4), metrics.dpi.toFixed(4)],
      ["RVPI", metrics.rvpi.toFixed(4), metrics.rvpi.toFixed(4)],
      ["TVPI", metrics.tvpi.toFixed(4), metrics.tvpi.toFixed(4)],
      [
        "Net IRR",
        metrics.netIrr != null ? `${(metrics.netIrr * 100).toFixed(2)}%` : "N/A",
        metrics.netIrr != null ? `${(metrics.netIrr * 100).toFixed(2)}%` : "N/A",
      ],
    ];

    doc.font("Helvetica-Bold").fontSize(11).text("Capital Account Summary (USD / ZiG)");
    doc.moveDown(0.3);
    doc.font("Helvetica").fontSize(10);
    for (const [label, usd, zig] of rows) {
      doc.text(`${label}: ${usd}  |  ${zig}`);
    }

    doc.moveDown(1);
    doc.fontSize(8).fillColor("#666666").text("Generated by Arcus Quarterly Statement Engine. SHA-256 verified on publish.");
    doc.end();
  });
}
