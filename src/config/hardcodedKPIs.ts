/**
 * Get all hardcoded KPIs
 */
export function getAllKPIs(): HardcodedKPI[] {
  return HARDCODED_KPIS;
}

/**
 * Get KPIs by department
 */
export function getKPIsByDepartment(department: string): HardcodedKPI[] {
  return HARDCODED_KPIS.filter(kpi => kpi.department === department);
}

/**
 * Get KPI by code
 */
export function getKPIByCode(code: string): HardcodedKPI | undefined {
  return HARDCODED_KPIS.find(kpi => kpi.code === code);
}

/**
 * Get all departments with their KPIs
 */
export function getAllDepartmentsWithKPIs(): DepartmentKPIs[] {
  const departments = ["Finance", "Sales", "Operations", "Procurement", "Human Resources", "Marketing", "Legal", "IT"];
  return departments.map(dept => ({
    department: dept,
    departmentCode: dept.toUpperCase().replace(/\s+/g, '_'),
    description: `${dept} Department`,
    kpis: getKPIsByDepartment(dept)
  }));
}

/**
 * Get department with KPIs
 */
export function getDepartmentWithKPIs(department: string): DepartmentKPIs | null {
  const kpis = getKPIsByDepartment(department);
  if (kpis.length === 0) {
    return null;
  }

  return {
    department: department,
    departmentCode: department.toUpperCase().replace(/\s+/g, '_'),
    description: `${department} Department`,
    kpis: kpis
  };
}

/**
 * Validate if KPI code exists
 */
export function isValidKPICode(code: string): boolean {
  return HARDCODED_KPIS.some(kpi => kpi.code === code);
}

/**
 * Get financial KPIs only
 */
export function getFinancialKPIs(): HardcodedKPI[] {
  return HARDCODED_KPIS.filter(kpi => kpi.isFinancial);
}

/**
 * Get KPIs that affect specific account type
 */
export function getKPIsByAccountType(accountType: 'Revenue' | 'Expense' | 'Asset' | 'Liability' | 'Equity'): HardcodedKPI[] {
  return HARDCODED_KPIS.filter(kpi => kpi.accountType === accountType);
}
